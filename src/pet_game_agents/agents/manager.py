"""Manager agent — loops the crew until the game is playable or retries run out."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

from ..state import BuildState
from ..templates import write_text

Route = Literal["design", "code", "done"]


def manager_node(state: BuildState) -> dict[str, Any]:
    """Record the outcome. Routing itself happens in the conditional edge."""
    playable = bool(state.get("playable"))
    retries = int(state.get("retries") or 0)
    max_retries = int(state.get("max_retries") or 3)
    report = state.get("test_report") or {}
    output_dir = Path(state["output_dir"])

    if playable:
        _write_output_readme(output_dir, state, success=True)
        return {
            "status": "playable",
            "log": ["manager: game is playable; stopping the loop"],
        }

    if retries >= max_retries:
        _write_output_readme(output_dir, state, success=False)
        summary = report.get("summary") or "unknown failure"
        return {
            "status": "failed",
            "log": [
                f"manager: still not playable after {retries} retry(ies); giving up ({summary})"
            ],
        }

    category = state.get("failure_category") or report.get("category") or "code"
    target = "designer" if category == "design" else "coder"
    return {
        "status": "running",
        "retries": retries + 1,
        "log": [
            f"manager: not playable ({category}); retry {retries + 1}/{max_retries} via {target}"
        ],
    }


def route_after_manager(state: BuildState) -> Route:
    """Route only on the Manager's decision; retries are counted in manager_node."""
    if state.get("playable") or state.get("status") == "playable":
        return "done"
    if state.get("status") == "failed":
        return "done"
    category = state.get("failure_category") or "code"
    if category == "design":
        return "design"
    return "code"


def _write_output_readme(output_dir: Path, state: BuildState, *, success: bool) -> None:
    design = state.get("design") or {}
    title = design.get("title") or "Little Companion"
    species = state.get("species") or design.get("species") or "pet"
    theme = state.get("theme") or design.get("theme") or ""
    name = design.get("pet_name_default") or "Mochi"
    if success:
        body = f"""# {title}

A cozy terminal pet-raising game (game nuôi thú) generated by the pet-game-agents pipeline.

- Species: {species}
- Theme: {theme}
- Default name: {name}

## Play

```bash
python pet_game.py
```

Commands: `[F]eed`, `[P]lay`, `[S]leep`, `[W]ait`, `[H]elp`, `[Q]uit`.

Keep hunger (fullness), happiness, and energy above zero. Care actions earn XP; reach level 5.

A non-interactive run:

```bash
python pet_game.py --script feed,play,sleep,feed,play,sleep
```

## Art

ASCII moods live in `sprites/ascii.json`. SVG portraits are in `sprites/pet_*.svg`.

## Tests

```bash
pytest tests
```
"""
    else:
        report = state.get("test_report") or {}
        body = f"""# Build did not finish

The manager stopped after reaching the retry limit. Last test summary:

{report.get('summary') or 'No report.'}

Inspect `design.json` and `pet_game.py`, then re-run the pipeline.
"""
    write_text(output_dir / "README.md", body)

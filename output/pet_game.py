def _clamp(value: int, lo: int, hi: int) -> int:
    return max(lo, min(hi, value))


def _stat_spec(name: str) -> dict[str, int]:
    stats = DESIGN.get("stats") or {}
    spec = dict(stats.get(name) or {})
    return {
        "min": int(spec.get("min", 0)),
        "max": int(spec.get("max", 100)),
        "start": int(spec.get("start", 70)),
        "decay_per_turn": int(spec.get("decay_per_turn", 6)),
    }


def _actions() -> list[dict[str, Any]]:
    actions = DESIGN.get("actions") or []
    if actions:
        return list(actions)
    return [
        {"id": "feed", "label": "Feed", "effects": {"hunger": 30, "energy": 5, "happiness": 5}},
        {"id": "play", "label": "Play", "effects": {"happiness": 25, "energy": -20, "hunger": -10}},
        {"id": "sleep", "label": "Sleep", "effects": {"energy": 40, "hunger": -8, "happiness": 5}},
    ]


def load_ascii() -> dict[str, str]:
    species = str(DESIGN.get("species") or "cat")
    path = SPRITES_DIR / "ascii.json"
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(data, dict) and data:
                return {str(k): str(v) for k, v in data.items()}
        except (OSError, json.JSONDecodeError):
            pass
    return dict(FALLBACK_ASCII.get(species, FALLBACK_ASCII["cat"]))


class Pet:
    """A virtual pet with hunger, happiness, energy, and a level."""

    def __init__(self, name: str | None = None, species: str | None = None) -> None:
        leveling = DESIGN.get("leveling") or {}
        self.species = species or str(DESIGN.get("species") or "cat")
        self.name = name or str(DESIGN.get("pet_name_default") or "Mochi")
        self.theme = str(DESIGN.get("theme") or "cozy companion")
        self.title = str(DESIGN.get("title") or "Little Companion")
        hunger = _stat_spec("hunger")
        happiness = _stat_spec("happiness")
        energy = _stat_spec("energy")
        self._bounds = {
            "hunger": (hunger["min"], hunger["max"]),
            "happiness": (happiness["min"], happiness["max"]),
            "energy": (energy["min"], energy["max"]),
        }
        self._decay = {
            "hunger": hunger["decay_per_turn"],
            "happiness": happiness["decay_per_turn"],
            "energy": energy["decay_per_turn"],
        }
        self.hunger = hunger["start"]
        self.happiness = happiness["start"]
        self.energy = energy["start"]
        self.level = 1
        self.xp = 0
        self.xp_per_action = int(leveling.get("xp_per_action", 10))
        self.xp_to_level = int(leveling.get("xp_to_level", 30))
        self.max_level = int(leveling.get("max_level", 5))
        self.turn = 0
        self.alive = True
        self.logs: list[str] = [f"{self.name} the {self.species} arrives, ready to be cared for."]
        self._ascii = load_ascii()

    def snapshot(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "species": self.species,
            "hunger": self.hunger,
            "happiness": self.happiness,
            "energy": self.energy,
            "level": self.level,
            "xp": self.xp,
            "turn": self.turn,
            "alive": self.alive,
            "mood": self.mood(),
        }

    def _apply(self, effects: dict[str, int], *, tick: bool = True, grant_xp: bool = True) -> dict[str, Any]:
        if not self.alive:
            return self.snapshot()
        for stat, delta in effects.items():
            if stat in self._bounds:
                lo, hi = self._bounds[stat]
                current = getattr(self, stat)
                setattr(self, stat, _clamp(current + int(delta), lo, hi))
        if grant_xp:
            self._gain_xp(self.xp_per_action)
        if tick:
            self.tick()
        return self.snapshot()

    def _gain_xp(self, amount: int) -> None:
        if self.level >= self.max_level:
            return
        self.xp += amount
        while self.xp >= self.xp_to_level and self.level < self.max_level:
            self.xp -= self.xp_to_level
            self.level += 1
            self.logs.append(f"{self.name} reached level {self.level}!")
            # A level-up is a little boost so the loop feels rewarding.
            lo_h, hi_h = self._bounds["happiness"]
            self.happiness = _clamp(self.happiness + 10, lo_h, hi_h)

    def feed(self) -> dict[str, Any]:
        action = next((a for a in _actions() if a.get("id") == "feed"), None)
        effects = dict((action or {}).get("effects") or {"hunger": 30, "energy": 5, "happiness": 5})
        self.logs.append(f"You feed {self.name}. The bowl is empty; the belly is not.")
        return self._apply(effects)

    def play(self) -> dict[str, Any]:
        if self.energy < 10:
            self.logs.append(f"{self.name} is too tired to play. A nap might help.")
            return self.snapshot()
        action = next((a for a in _actions() if a.get("id") == "play"), None)
        effects = dict((action or {}).get("effects") or {"happiness": 25, "energy": -20, "hunger": -10})
        self.logs.append(f"You play with {self.name}. Joy goes up; energy goes down.")
        return self._apply(effects)

    def sleep(self) -> dict[str, Any]:
        action = next((a for a in _actions() if a.get("id") == "sleep"), None)
        effects = dict((action or {}).get("effects") or {"energy": 40, "hunger": -8, "happiness": 5})
        self.logs.append(f"{self.name} curls up and sleeps. Energy returns.")
        return self._apply(effects)

    def wait(self) -> dict[str, Any]:
        self.logs.append("A quiet moment passes.")
        if not self.alive:
            return self.snapshot()
        self.tick()
        return self.snapshot()

    def tick(self) -> None:
        """Advance one turn and apply idle decay. Called after most actions."""
        self.turn += 1
        for stat, decay in self._decay.items():
            lo, hi = self._bounds[stat]
            setattr(self, stat, _clamp(getattr(self, stat) - decay, lo, hi))
        if self.hunger <= 0 or self.happiness <= 0 or self.energy <= 0:
            self.alive = False
            self.logs.append(
                f"Oh no — {self.name} needs more care. One of the stats reached zero. Game over."
            )

    def mood(self) -> str:
        if not self.alive:
            return "sad"
        if self.energy <= 25:
            return "sleepy"
        if self.hunger <= 25:
            return "hungry"
        if self.happiness <= 25:
            return "sad"
        if self.happiness >= 70 and self.energy >= 40:
            return "play" if self.happiness >= 85 else "happy"
        return "happy"

    def ascii_art(self) -> str:
        mood = self.mood()
        return self._ascii.get(mood) or self._ascii.get("happy") or "(?:)"

    def bar(self, value: int, stat: str = "hunger") -> str:
        lo, hi = self._bounds.get(stat, (0, 100))
        width = 10
        span = max(hi - lo, 1)
        filled = int(round((value - lo) / span * width))
        filled = _clamp(filled, 0, width)
        return "[" + "#" * filled + "." * (width - filled) + f"]  {value}"

    def status_text(self) -> str:
        lines = [
            self.ascii_art(),
            "",
            f" {self.name} the {self.species}    Level {self.level} ({self.xp}/{self.xp_to_level} XP)",
            f" Hunger    {self.bar(self.hunger, 'hunger')}",
            f" Happiness {self.bar(self.happiness, 'happiness')}",
            f" Energy    {self.bar(self.energy, 'energy')}",
            f" Mood: {self.mood()}    Turn: {self.turn}",
        ]
        if not self.alive:
            lines.append(" Status: needs a fresh start (game over)")
        return "\n".join(lines)


def run_scripted(commands: list[str], name: str | None = None) -> dict[str, Any]:
    """Play a non-interactive session. Used by the Tester agent and pytest."""
    pet = Pet(name=name)
    history: list[dict[str, Any]] = [pet.snapshot()]
    for raw in commands:
        cmd = raw.strip().lower()
        if cmd in {"f", "feed"}:
            history.append(pet.feed())
        elif cmd in {"p", "play"}:
            history.append(pet.play())
        elif cmd in {"s", "sleep"}:
            history.append(pet.sleep())
        elif cmd in {"w", "wait", "t", "tick"}:
            history.append(pet.wait())
        elif cmd in {"q", "quit"}:
            break
        elif cmd in {"status", "st"}:
            history.append(pet.snapshot())
        else:
            pet.logs.append(f"Unknown command: {raw}")
    return {"final": pet.snapshot(), "history": history, "logs": list(pet.logs), "alive": pet.alive}


def _help_text(pet: Pet) -> str:
    return "\n".join(
        [
            f"{pet.title} — {pet.theme}",
            "Hunger, happiness, and energy all go down a little every turn.",
            "  [F]eed   fill the belly (hunger goes up)",
            "  [P]lay   boost happiness, spend energy and a bit of hunger",
            "  [S]leep  restore energy, get a little hungry",
            "  [W]ait   skip a turn (stats still decay)",
            "  [H]elp   show this help",
            "  [Q]uit   leave the game",
            f"Reach level {pet.max_level} by caring for your pet. Don't let any stat hit zero.",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Play the generated pet-raising game.")
    parser.add_argument("--name", help="Pet name (default comes from the design).")
    parser.add_argument(
        "--script",
        help="Comma-separated commands for a non-interactive run (e.g. feed,play,sleep).",
    )
    args = parser.parse_args(argv)
    if args.script:
        commands = [part.strip() for part in args.script.split(",") if part.strip()]
        result = run_scripted(commands, name=args.name)
        print(json.dumps(result["final"], indent=2))
        print("alive:" , result["alive"])
        return 0 if result["alive"] else 2

    pet = Pet(name=args.name)
    title = f"  {pet.title}"
    print("=" * 40)
    print(title)
    print(f"  ({pet.theme})")
    print("=" * 40)
    print(_help_text(pet))
    print()
    while True:
        print(pet.status_text())
        print()
        if not pet.alive:
            print("Thanks for playing. Run the game again to start fresh.")
            return 2
        if pet.level >= pet.max_level:
            print(f"{pet.name} is thriving at max level. You can keep playing or quit.")
        try:
            raw = input("What would you like to do? [F/P/S/W/H/Q] > ").strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\nGoodbye!")
            return 0
        if raw in {"q", "quit", "exit"}:
            print(f"Bye! {pet.name} will be here next time.")
            return 0
        if raw in {"h", "help", "?"}:
            print(_help_text(pet))
            continue
        if raw in {"f", "feed"}:
            pet.feed()
        elif raw in {"p", "play"}:
            pet.play()
        elif raw in {"s", "sleep"}:
            pet.sleep()
        elif raw in {"w", "wait", "t", "tick", ""}:
            pet.wait()
        elif raw in {"st", "status"}:
            continue
        else:
            print("I don't know that command. Try F, P, S, W, H, or Q.")
        print()


if __name__ == "__main__":
    sys.exit(main())
